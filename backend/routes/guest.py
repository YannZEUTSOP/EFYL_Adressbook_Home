"""Guest identity — every device gets a real, recoverable identity.

Field reality: most surveyors start in guest mode. Before this module, guest
data was tied to an anonymous per-device key, so clearing the browser/app
storage orphaned the work. Now a guest gets:
  • a shareable identifier  EFYL-G-XXXXXX
  • a 4-digit PIN generated by the server (shown once)
  • a device fingerprint registered server-side, so a returning device is
    recognised even after its local storage was wiped.

The fingerprint is only a HINT (a factory reset or an iOS reinstall changes
it) — the PIN always remains mandatory to open an account.
"""
import re
import secrets
from datetime import datetime, timezone, timedelta
from typing import List, Optional

import bcrypt
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from shared import (db, make_ref_token, make_token, norm_text, now_iso,
                    read_ref_token)

router = APIRouter(prefix="/api/guest")

_DUMMY_PIN_HASH = bcrypt.hashpw(b"0000-dummy-pin", bcrypt.gensalt())
_WEAK_PINS = {"0000", "1111", "2222", "3333", "4444", "5555", "6666", "7777",
              "8888", "9999", "1234", "4321", "1212", "0123"}
MAX_CANDIDATES = 8


class DeviceCheckRequest(BaseModel):
    device_hash: str
    device_label: Optional[str] = ""


class GuestRegisterRequest(BaseModel):
    name: str
    device_hash: str
    device_id: str
    device_label: Optional[str] = ""


class GuestLookupRequest(BaseModel):
    name: str
    device_hash: Optional[str] = ""


class GuestLoginRequest(BaseModel):
    pin: str
    ref: Optional[str] = None        # opaque candidate reference (preferred)
    guest_id: Optional[str] = None   # or the full EFYL-G-XXXXXX identifier
    device_hash: Optional[str] = ""
    device_label: Optional[str] = ""


def _gen_pin() -> str:
    while True:
        pin = f"{secrets.randbelow(10000):04d}"
        if pin not in _WEAK_PINS:
            return pin


def _mask(guest_id: str) -> str:
    if not guest_id:
        return ""
    return f"{guest_id[:7]}••••{guest_id[-2:]}" if len(guest_id) > 9 else guest_id


async def _addresses_count(user_id: str) -> int:
    return await db.addresses.count_documents({"owner_id": user_id})


async def _candidate_payload(u: dict, device_hash: str = "") -> dict:
    devices = u.get("devices") or []
    return {
        "ref": make_ref_token(u["user_id"]),
        "guest_id_masked": _mask(u.get("guest_id", "")),
        "name": u.get("name", ""),
        "last_login": u.get("last_login", ""),
        "created_at": u.get("created_at", ""),
        "addresses_count": await _addresses_count(u["user_id"]),
        "same_device": any(d.get("hash") == device_hash for d in devices) if device_hash else False,
    }


async def _register_device(user_id: str, device_hash: str, device_label: str = "") -> None:
    if not device_hash:
        return
    user = await db.users.find_one({"user_id": user_id}, {"_id": 0, "devices": 1})
    devices = (user or {}).get("devices") or []
    found = False
    for d in devices:
        if d.get("hash") == device_hash:
            d["last_seen"] = now_iso()
            if device_label:
                d["label"] = device_label
            found = True
    if not found:
        devices.append({"hash": device_hash, "label": device_label,
                        "first_seen": now_iso(), "last_seen": now_iso()})
    await db.users.update_one({"user_id": user_id}, {"$set": {"devices": devices}})


@router.post("/device-check")
async def device_check(payload: DeviceCheckRequest):
    """Has this physical device ever opened an account? Used to offer
    'Reprendre : Yann (EFYL-G-••••C3)' after a storage wipe."""
    if not payload.device_hash:
        return {"known": False, "accounts": []}
    accounts: List[dict] = []
    cursor = db.users.find(
        {"devices.hash": payload.device_hash},
        {"_id": 0, "user_id": 1, "guest_id": 1, "efyl_id": 1, "name": 1,
         "phone": 1, "is_guest": 1, "last_login": 1, "created_at": 1, "devices": 1},
    ).sort("last_login", -1).limit(MAX_CANDIDATES)
    async for u in cursor:
        item = await _candidate_payload(u, payload.device_hash)
        item["is_guest"] = bool(u.get("is_guest"))
        if not u.get("is_guest"):
            # phone account: identify it by its EFYL id instead
            item["guest_id_masked"] = _mask(u.get("efyl_id", ""))
        accounts.append(item)
    return {"known": bool(accounts), "accounts": accounts}


@router.post("/register")
async def guest_register(payload: GuestRegisterRequest):
    """Create a guest account. The identifier + PIN are returned ONCE."""
    name = payload.name.strip()
    if len(name) < 2:
        raise HTTPException(400, "Name must have at least 2 characters")

    # Keep the historical per-device owner id when it is free: all the work
    # already recorded on this device stays attached to the new account.
    candidate = f"guest-{payload.device_id.strip()}" if payload.device_id.strip() else ""
    if candidate:
        clash = await db.users.find_one({"user_id": candidate}, {"_id": 0, "user_id": 1})
        if clash:
            candidate = ""
    user_id = candidate or f"guest-{secrets.token_hex(6)}"

    for _ in range(6):
        guest_id = f"EFYL-G-{secrets.token_hex(3).upper()}"
        if not await db.users.find_one({"guest_id": guest_id}, {"_id": 0, "guest_id": 1}):
            break
    else:
        raise HTTPException(500, "Could not allocate an identifier, try again")

    pin = _gen_pin()
    await db.users.update_one(
        {"user_id": user_id},
        {"$set": {
            "user_id": user_id,
            "guest_id": guest_id,
            "is_guest": True,
            "name": name,
            "name_norm": norm_text(name),
            "pin_hash": bcrypt.hashpw(pin.encode("utf-8"), bcrypt.gensalt()).decode("utf-8"),
            "failed_pin_attempts": 0,
            "locked_until": None,
            "last_login": now_iso(),
        }, "$setOnInsert": {"created_at": now_iso()}},
        upsert=True,
    )
    await _register_device(user_id, payload.device_hash, payload.device_label or "")
    return {"user_id": user_id, "guest_id": guest_id, "name": name,
            "pin": pin, "token": make_token(user_id),
            "addresses_count": await _addresses_count(user_id)}


@router.post("/lookup")
async def guest_lookup(payload: GuestLookupRequest):
    """Find guest accounts by first name (case & accent insensitive).
    Identifiers are always returned MASKED — the account can only be opened
    with its PIN through the opaque `ref`."""
    needle = norm_text(payload.name)
    if len(needle) < 2:
        raise HTTPException(400, "Enter at least 2 characters")
    safe = re.escape(needle)
    found: List[dict] = []
    seen = set()
    # exact normalised name first, then "starts with", then "contains"
    for query in (
        {"is_guest": True, "name_norm": needle},
        {"is_guest": True, "name_norm": {"$regex": f"^{safe}"}},
        {"is_guest": True, "name_norm": {"$regex": safe}},
    ):
        cursor = db.users.find(
            query,
            {"_id": 0, "user_id": 1, "guest_id": 1, "name": 1, "last_login": 1,
             "created_at": 1, "devices": 1},
        ).sort("last_login", -1).limit(MAX_CANDIDATES * 2)
        async for u in cursor:
            if u["user_id"] in seen:
                continue
            seen.add(u["user_id"])
            found.append(u)
            if len(found) >= MAX_CANDIDATES:
                break
        if len(found) >= MAX_CANDIDATES:
            break
    candidates = [await _candidate_payload(u, payload.device_hash or "") for u in found]
    # most recent first, then accounts already seen on this device on top
    candidates.sort(key=lambda c: c["last_login"] or "", reverse=True)
    candidates.sort(key=lambda c: not c["same_device"])
    return {"count": len(candidates), "candidates": candidates}


@router.post("/login")
async def guest_login(payload: GuestLoginRequest):
    """Open a guest account with its PIN (5 wrong tries → 15 min lock)."""
    pin = payload.pin.strip()
    if not (pin.isdigit() and len(pin) == 4):
        raise HTTPException(400, "PIN must be exactly 4 digits")

    user = None
    if payload.ref:
        user_id = read_ref_token(payload.ref)
        user = await db.users.find_one({"user_id": user_id}, {"_id": 0})
    elif payload.guest_id:
        user = await db.users.find_one(
            {"guest_id": payload.guest_id.strip().upper()}, {"_id": 0}
        )
    if not user or not user.get("pin_hash"):
        bcrypt.checkpw(pin.encode("utf-8"), _DUMMY_PIN_HASH)  # anti-enumeration
        raise HTTPException(401, "Invalid identifier or PIN")

    now = datetime.now(timezone.utc)
    locked = user.get("locked_until")
    if locked and locked > now.isoformat():
        raise HTTPException(429, "Too many attempts. Try again in 15 minutes.")
    if not bcrypt.checkpw(pin.encode("utf-8"), user["pin_hash"].encode("utf-8")):
        fails = int(user.get("failed_pin_attempts", 0)) + 1
        upd = {"failed_pin_attempts": fails}
        if fails >= 5:
            upd = {"failed_pin_attempts": 0,
                   "locked_until": (now + timedelta(minutes=15)).isoformat()}
        await db.users.update_one({"user_id": user["user_id"]}, {"$set": upd})
        raise HTTPException(401, "Invalid identifier or PIN")

    await db.users.update_one(
        {"user_id": user["user_id"]},
        {"$set": {"failed_pin_attempts": 0, "locked_until": None,
                  "last_login": now.isoformat()}},
    )
    await _register_device(user["user_id"], payload.device_hash or "",
                           payload.device_label or "")
    return {"user_id": user["user_id"],
            "guest_id": user.get("guest_id", ""),
            "efyl_id": user.get("efyl_id", ""),
            "name": user.get("name", ""),
            "is_guest": bool(user.get("is_guest")),
            "token": make_token(user["user_id"]),
            "addresses_count": await _addresses_count(user["user_id"])}
